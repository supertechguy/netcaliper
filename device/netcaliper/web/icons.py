def _svg(rows: tuple[str, ...], w: int, h: int, cls: str, label: str) -> str:
    rects = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == "#":
                x0 = x
                while x < len(row) and row[x] == "#":
                    x += 1
                rects.append(f'<rect x="{x0}" y="{y}" width="{x - x0}" height=".78"/>')  # scanline gap
            else:
                x += 1
    aria = f'role="img" aria-label="{label}"' if label else 'aria-hidden="true"'
    return (
        f'<svg class="{cls}" viewBox="0 0 {w} {h}" {aria} fill="currentColor" '
        f'shape-rendering="crispEdges">{"".join(rects)}</svg>'
    )


@cache
def icon(name: str, cls: str = "ico") -> Markup:
    rows = ICONS.get(name)
    if rows is None:
        return Markup("")
    return Markup(_svg(rows, N, N, cls, ""))  # noqa: S704 - generated from the constant grids above


@cache
def wordmark(text: str = "netcaliper") -> Markup:
    """The splash wordmark (same 5x9 pixel font) for the status bar."""
    rows = ["" for _ in range(GLYPH_ROWS)]
    for i, ch in enumerate(text):
        for y in range(GLYPH_ROWS):
            rows[y] += GLYPHS[ch][y] + ("." if i < len(text) - 1 else "")
    grid = tuple(r.replace(" ", ".") for r in rows)
    return Markup(_svg(grid, len(grid[0]), GLYPH_ROWS, "wordmark", text))  # noqa: S704 - constant glyphs
