// Generate src/records.gen.ts from the device's JSON Schemas (/schemas, the device<->cloud contract).
// `--check` exits non-zero when the committed file is stale (CI).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemas = join(here, "..", "..", "schemas");
const out = join(here, "..", "src", "records.gen.ts");

let text =
  "// SPDX-License-Identifier: GPL-3.0-only\n" +
  "// GENERATED by scripts/gen-types.mjs from /schemas — do not edit. Run `npm run types`.\n\n";
const kinds = {};
// Property titles would become one type alias per field (Id, RunId, …) that collide across schemas.
function untitle(node, top = false) {
  if (Array.isArray(node)) return node.map((n) => untitle(n));
  if (node && typeof node === "object") {
    const o = {};
    for (const [k, v] of Object.entries(node)) {
      if (k === "title" && !top && typeof v === "string" && !("properties" in node)) continue;
      o[k] = untitle(v);
    }
    return o;
  }
  return node;
}
for (const name of readdirSync(schemas).filter((n) => n.endsWith(".schema.json")).sort()) {
  const schema = untitle(JSON.parse(readFileSync(join(schemas, name), "utf8")), true);
  const meta = schema["x-netcaliper"];
  kinds[meta.kind] = { title: schema.title, schema_version: meta.schema_version };
  const ts = await compile(schema, schema.title, {
    bannerComment: "",
    additionalProperties: false,
    declareExternallyReferenced: true,
    format: true,
    style: { singleQuote: false, printWidth: 110 },
  });
  text += `// ---- ${meta.kind} (schema_version ${meta.schema_version})\n${ts}\n`;
}
// Dedupe definitions shared between schemas (e.g. ArtifactRef) — keep the first.
const seen = new Set();
text = text.replace(/^(\/\*\*[\s\S]*?\*\/\n)?export interface (\w+) \{\n[\s\S]*?^\}\n/gm, (block, _doc, n) => {
  if (seen.has(n)) return "";
  seen.add(n);
  return block;
});
text += `\nexport const SCHEMA_VERSIONS = ${JSON.stringify(
  Object.fromEntries(Object.entries(kinds).map(([k, v]) => [k, v.schema_version])),
)} as const;\n`;
text += "export type RecordKind = keyof typeof SCHEMA_VERSIONS;\n";

if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(out, "utf8");
  } catch {}
  if (cur !== text) {
    console.error("src/records.gen.ts is stale — run `npm run types` in cloud/");
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
}
